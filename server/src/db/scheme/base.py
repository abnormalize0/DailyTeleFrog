from sqlalchemy.orm import DeclarativeBase


# Правило сравнения строк во всех таблицах — utf8mb4_0900_ai_ci, значение MySQL 8
# по умолчанию: ни схема, ни настройки базы его не задают. Оно не учитывает
# регистр и диакритику, поэтому для базы `Bob` и `bob`, `Игра` и `игра`, `е` и `ё`
# — одно и то же значение. Отсюда два следствия: такие значения не могут
# сосуществовать в первичных и unique-ключах (username, email, tag_name), а WHERE
# находит оба варианта. Python-сравнение (==, set) их различает, поэтому проверять
# равенство таких значений надо в базе, как в article.py::add_tags.
