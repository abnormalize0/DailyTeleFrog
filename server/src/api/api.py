"""
Этот файл служит точкой сборки API: подключает общий Flask-app и хелперы из
`shared.py`, регистрирует все методы через импорт пакета `routes` и запускает
сервер.

API устроено по классическому REST (см. decisions/0004-rest-api.md).
Пометка для добавления нового API метода:
1. Названия методов формируются следующим образом: api_%METHOD_NAME%_%REQUEST_TYPE%
Префикс api_ обязателен. Остальная часть названия метода позволяет избежать
дублирования названий функций.
2. Для каждого метода должен присутствовать тест в файле
/server/tests/routes/test_%RESOURCE%.py и описание в ответе на запрос OPTIONS в
файле /server/src/api/api_info.py
3. Личность вызывающего определяется access token'ом из заголовка
Authorization: Bearer <token> (см. require_auth/optional_auth), а не полем
username в теле запроса. Внутри слоёв backend/db неавторизованный пользователь
обозначается значением `None` (см. decisions/0008-anonymous-user.md) — это деталь
реализации, наружу (клиенту) она не передаётся.
4. Метод отвечает настоящим HTTP-кодом. Тело успешного ответа содержит только
данные, ошибка отдаётся в формате Problem Details (см. request_status.py).
5. Последовательность API методов должна быть одинаковой для файла метода,
документации, тестов и запросов OPTIONS.
6. Каждый запрос должен быть декорирован таймером и логгированием принимаемых аргументов.
Логгирование аргументов позволит облегчить поиск проблем, когда такие возникнут.
Таймер позволит иметь конкретные значения времени выполнения запроса, что облегчит решение проблем аля "ВСЕ ТОРМОЗИТ!!!"
7. Параметры GET передаются в query-строке, данные POST/PUT/PATCH — в JSON-теле,
идентификатор ресурса — в пути.
Новый метод добавляется в src/api/routes/ в свой отдельный файл (или в файл
уже существующего ресурса, если метод делит с ним путь) и регистрируется
автоматически через импорт пакета routes ниже.
"""

import os

from . import shared
from . import routes  # noqa: F401  (импорт триггерит регистрацию @app.route)


def run_server(server_mode: str = "production") -> None:
    """Запускает Flask-сервер, выбрав URL базы данных из переменных окружения.

    Args:
        server_mode: "production" или "test".

    Returns:
        None
    """
    if server_mode == "test":
        shared.db_url = os.getenv("MVP_DB_URL_TEST")
    else:
        shared.db_url = os.getenv("MVP_DB_URL_PRODUCTION")
    shared.app.run(host="0.0.0.0", port=5000)
